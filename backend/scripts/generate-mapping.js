const result = [];
const engToIds = {};

items.forEach(item => {
  let eng = dict[item.name];
  if (!eng) {
    eng = vietnameseSlugify(item.name).replace(/-/g, ' ');
  }
  
  const key = eng.toLowerCase() + '-' + item.foodType; // Dedup based on english name AND foodType
  if (!engToIds[key]) {
    engToIds[key] = [];
  }
  engToIds[key].push(item.id);

  result.push({
    id: item.id,
    vietnamese: item.name,
    english: eng,
    foodType: item.foodType,
    category: item.category,
    filename: vietnameseSlugify(item.name) + '.webp',
    shared_with_ids: [] // computed below
  });
});

result.forEach(r => {
  const key = r.english.toLowerCase() + '-' + r.foodType;
  const allIds = engToIds[key];
  r.shared_with_ids = allIds.filter(id => id !== r.id);
  if (r.shared_with_ids.length > 0) {
    // Only the first one in the list handles generation. Others just reference.
    if (r.id !== allIds[0]) {
        r._note = `Dùng chung ảnh với ID ${allIds[0]} — chỉ generate 1 lần`;
    }
  }
});

fs.writeFileSync(path.resolve(__dirname, '../scratch/food_name_mapping.json'), JSON.stringify(result, null, 2), 'utf-8');
